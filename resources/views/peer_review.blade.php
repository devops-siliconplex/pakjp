                            <div class="entry-content">
                                <p> Pakistan Journal of Pharmacology (PAKJP) requires the Peer Reviewers to review these guidelines before evaluating the manuscript. After reading this, the reviewer should have most of their questions answered. It will also help them complete a peer review report as thoroughly and efficiently as possible, ensuring that the work is properly evaluated and published on time. The reviewers are advised to contact our editorial office if they have any additional queries.</p>

                                <p><strong>Importance of Peer Review:</strong> The Editor in Chief uses the feedback and suggestions from peer reviewers as a crucial source of information when choosing a manuscript. Peer review ensures that articles receive objective criticism and knowledgeable input, enabling writers to make improvements and, consequently, publish high-caliber scientific studies and reviews. In cases where peer reviewer comments are accessible, it also helps readers make educated decisions and trust the article's scientific integrity.</p>

                                <p><strong>Journal’s View on Peer Evaluation:</strong> PAKJP works hard to handle documents in a fair, timely, and comprehensive manner. Peer reviewers are therefore requested to submit their feedback within seven business days for Ultra-Fast Review (UFR), within ten business days for Fast Publication System (FPS) and within twenty-one business days for Regular Publication System (RPS). All submissions to the journal are subject to a double-anonymous peer review process. Reviewers are required to,</p>

                                <p>• respond promptly to review requests, even if they cannot complete the review, to avoid unnecessary delays in the process.</p>

                                <p>• disclose any conflicts of interest they may have (ask the publisher for clarification if in doubt) and be well-versed in the subject matter to evaluate the paper thoroughly. Additional details regarding conflicting interests are available on the PAKJP Website.</p>

                                <p>• maintain the confidentiality of any information pertaining to the authors' identities and the substance of the article.</p>
                                
                                <p>• give helpful and corrective comments rather than antagonistic or disparaging.</p>
                                
                                <p>• avoid placing any unpublished article files, photos, or other material into publicly accessible databases or tools (such as ChatGPT, generative AI tools) that do not maintain confidentiality, and are open to the public, or may keep or utilize the data for their own gain.</p>
                                
                                <p>• not to create review reports using artificial intelligence tools.</p>

                                <p>• use reliable and correct references in their evaluation report.</p>

                                <p>• maintain unbiasedness based on the origins of a manuscript, a writer's nationality, their political or religious views, their gender, or any other aspect of their identity. Reviewers should not let these factors influence their reviews, nor should they allow commercial concerns to have any influence.</p>
