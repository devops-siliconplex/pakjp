                <h2>How to make a Complaint</h2>
                <p>The Pakistan Journal of Pharmacology (PAKJP) office can be contacted by email at pjps@uok.edu.pk. Authors can use this address to file a formal complaint about any Editorial Staff, Peer Reviewer/Editorial Board Member (including an appeal against suspected coerced citation, or if a reviewer is suspected of appropriating author material), the publisher, and/or publishing policies or processes. The email subject line should read "Complaint," and the body should include an explanation of the reason for the complaint. Action on any complaint will be prioritized and processed further.</p>

                <p> <strong>Processing steps:</strong>
                <p><strong>Step 1:</strong> The PAKJP office will review the complaint request. The individual who is the subject of the complaint will not handle complaints about editorial staff, peer reviewers, or members of the editorial board to prevent any potential conflicts of interest.                    <br>
                    <p><strong>Step 2:</strong>The complaint will be thoroughly examined in compliance with all applicable PAKJP policies and procedures. </p>
                   <p><strong>Step 3:</strong>Corrective measures will be implemented immediately if the complaint is verified. Retraining of the editorial staff, peer reviewers, and editorial board members is one of these measures, as is the removal or dismissal of them, if necessary, as well as the revision and enhancement of any relevant publication policies or procedures. The type of complaint will determine the criterion for choosing the right action or actions.</p>
                     <p><strong>Step 4:</strong> The complainant will be informed regarding the outcome of the complaint.</p>

